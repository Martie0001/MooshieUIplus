import { MAX_INPUT_PIXELS_INPAINT, normalizeGenerationInputBytes } from "./editImagePreparation.js";

export type OutpaintDirection = "top" | "bottom" | "left" | "right" | "all";
export type OutpaintAmountUnit = "percent" | "pixels";

export interface OutpaintGeometry {
  left: number;
  right: number;
  top: number;
  bottom: number;
  width: number;
  height: number;
}

/**
 * Use the source's own width for left/right percentages and height for top/bottom.
 * Round each requested extension upward to an 8px grid so small percentages
 * are never silently lost. ComfyUI output dimensions also use the 8px grid.
 */
export function calculateOutpaintGeometry(
  sourceWidth: number,
  sourceHeight: number,
  direction: OutpaintDirection,
  unit: OutpaintAmountUnit,
  amount: number,
): OutpaintGeometry {
  if (!Number.isInteger(sourceWidth) || !Number.isInteger(sourceHeight) || sourceWidth < 1 || sourceHeight < 1) {
    throw new Error("來源圖片尺寸無效");
  }
  if (unit === "pixels") {
    if (!Number.isInteger(amount) || amount < 64 || amount > 768 || amount % 8 !== 0) {
      throw new Error("像素延伸量必須是 64–768 之間的 8 像素倍數");
    }
  } else if (unit === "percent") {
    if (!Number.isInteger(amount) || amount < 5 || amount > 100 || amount % 5 !== 0) {
      throw new Error("延伸比例必須是 5–100%，以 5% 為單位");
    }
  } else {
    throw new Error("不支援的延伸單位");
  }
  const align8 = (n: number) => Math.ceil(n / 8) * 8;
  const horizontal = unit === "pixels" ? amount : align8(sourceWidth * amount / 100);
  const vertical = unit === "pixels" ? amount : align8(sourceHeight * amount / 100);
  let left = direction === "left" || direction === "all" ? horizontal : 0;
  let right = direction === "right" || direction === "all" ? horizontal : 0;
  let top = direction === "top" || direction === "all" ? vertical : 0;
  let bottom = direction === "bottom" || direction === "all" ? vertical : 0;
  if (left + right + top + bottom === 0) throw new Error("請選擇有效延伸方向");
  const width = align8(sourceWidth + left + right);
  const height = align8(sourceHeight + top + bottom);
  // Attribute any 1–7px grid remainder to the selected edge where possible.
  if (left && !right) left += width - sourceWidth - left;
  else right += width - sourceWidth - left - right;
  if (top && !bottom) top += height - sourceHeight - top;
  else bottom += height - sourceHeight - top - bottom;
  if (width * height > MAX_INPUT_PIXELS_INPAINT || width > 4096 || height > 4096) {
    throw new Error("延伸後超過 4MP 上限，請縮小比例或先縮小來源圖片");
  }
  return { left, right, top, bottom, width, height };
}

export interface OutpaintPrepared {
  imageBytes: number[];
  maskBytes: number[];
  imageWidth: number;
  imageHeight: number;
  sourceWidth: number;
  sourceHeight: number;
}

/** Extends the source canvas without modifying the source pixels.
 * White mask pixels are generated by the inpainting backend; black pixels are protected.
 */
export async function prepareOutpaint(
  bytes: number[],
  direction: OutpaintDirection,
  amount: number,
  unit: OutpaintAmountUnit = "pixels",
): Promise<OutpaintPrepared> {
  const normalized = await normalizeGenerationInputBytes(bytes, "creative_outpaint_source.png", MAX_INPUT_PIXELS_INPAINT);
  try {
    const source = await createImageBitmap(normalized.previewBlob);
    try {
      const { left, top, width, height } = calculateOutpaintGeometry(
        source.width, source.height, direction, unit, amount,
      );
      const imageCanvas = document.createElement("canvas");
      imageCanvas.width = width;
      imageCanvas.height = height;
      const imageCtx = imageCanvas.getContext("2d");
      if (!imageCtx) throw new Error("無法建立擴圖畫布");
      // Extend the source's edge pixels so partial denoising cannot reveal a gray placeholder.
      const right = width - left - source.width;
      const bottom = height - top - source.height;
      imageCtx.drawImage(source, left, top);
      if (left) imageCtx.drawImage(source, 0, 0, 1, source.height, 0, top, left, source.height);
      if (right) imageCtx.drawImage(source, source.width - 1, 0, 1, source.height, left + source.width, top, right, source.height);
      if (top) imageCtx.drawImage(source, 0, 0, source.width, 1, left, 0, source.width, top);
      if (bottom) imageCtx.drawImage(source, 0, source.height - 1, source.width, 1, left, top + source.height, source.width, bottom);
      if (left && top) imageCtx.drawImage(source, 0, 0, 1, 1, 0, 0, left, top);
      if (right && top) imageCtx.drawImage(source, source.width - 1, 0, 1, 1, left + source.width, 0, right, top);
      if (left && bottom) imageCtx.drawImage(source, 0, source.height - 1, 1, 1, 0, top + source.height, left, bottom);
      if (right && bottom) imageCtx.drawImage(source, source.width - 1, source.height - 1, 1, 1, left + source.width, top + source.height, right, bottom);

      const maskCanvas = document.createElement("canvas");
      maskCanvas.width = width;
      maskCanvas.height = height;
      const maskCtx = maskCanvas.getContext("2d");
      if (!maskCtx) throw new Error("無法建立擴圖遮罩");
      maskCtx.fillStyle = "#ffffff";
      maskCtx.fillRect(0, 0, width, height);
      maskCtx.fillStyle = "#000000";
      maskCtx.fillRect(left, top, source.width, source.height);

      return {
        imageBytes: await encodePng(imageCanvas),
        maskBytes: await encodePng(maskCanvas),
        imageWidth: width,
        imageHeight: height,
        sourceWidth: source.width,
        sourceHeight: source.height,
      };
    } finally {
      source.close();
    }
  } finally {
    URL.revokeObjectURL(normalized.previewUrl);
  }
}

async function encodePng(canvas: HTMLCanvasElement): Promise<number[]> {
  const blob = await new Promise<Blob>((resolve, reject) =>
    canvas.toBlob(value => value ? resolve(value) : reject(new Error("PNG 輸出失敗")), "image/png")
  );
  return Array.from(new Uint8Array(await blob.arrayBuffer()));
}
